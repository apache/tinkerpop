package org.apache.tinkerpop.gremlin.structure.snapshot.process.strategy;

/**
 * Thrown while planning when a step, a child traversal or a whole traversal cannot be proven equivalent natively. It
 * is never visible outside the strategy: the planner turns it into a debug log line and leaves the steps on facades.
 */
final class Reject extends RuntimeException {

    Reject(final String reason) {
        super(reason, null, false, false);
    }
}
