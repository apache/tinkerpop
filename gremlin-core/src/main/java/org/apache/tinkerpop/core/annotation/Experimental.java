package org.apache.tinkerpop.core.annotation;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Identifies an API as experimental. Experimental APIs are not covered by the usual backward-compatibility guarantee
 * and may have breaking changes or be removed in a subsequent minor release.
 *
 * @since 3.8.3
 */
@Documented
@Retention(RetentionPolicy.CLASS)
@Target({
        ElementType.ANNOTATION_TYPE,
        ElementType.CONSTRUCTOR,
        ElementType.FIELD,
        ElementType.METHOD,
        ElementType.PACKAGE,
        ElementType.TYPE})
public @interface Experimental {
}
